#!/usr/bin/env bun
/**
 * Bundle `mod-projection.ts` into `plugin/hooks/projection.js`, which the mod imports. The output is
 * committed, because the plugin is installed from the repository as it stands, without a build.
 * `hook-test/unit/mod-projection.test.ts` fails when it is stale.
 *
 * esbuild, pinned in package.json, makes the bundle: its output is the same on every machine, which
 * Bun's bundler, whose version the CI and each developer pick, does not promise.
 */

import { join } from 'node:path';
import { build } from 'esbuild';

const ROOT = join(import.meta.dir, '..');
export const PROJECTION_FILE = join(ROOT, 'plugin/hooks/projection.js');

const BANNER =
  '// Generated by scripts/build-mod-projection.ts from structured-context/browser and structured-context-map-views.\n' +
  '// Do not edit: run `bun run build:mod-projection`.';

export async function buildModProjection(): Promise<string> {
  const result = await build({
    entryPoints: [join(import.meta.dir, 'mod-projection.ts')],
    absWorkingDir: ROOT,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    mainFields: ['module', 'main'],
    // The pre-push check runs in a worktree whose node_modules is a symlink; keep its paths in the comments
    preserveSymlinks: true,
    banner: { js: BANNER },
    write: false,
    logLevel: 'silent',
  });
  // The comments naming each input are relative to absWorkingDir, so the same in any checkout
  return result.outputFiles[0]!.text;
}

if (import.meta.main) {
  await Bun.write(PROJECTION_FILE, await buildModProjection());
}
