import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import type { AnySchemaObject } from 'ajv';
import type { Config, SpaceConfig } from '../config';
import { resourceDir, SCHEMAS_RESOURCE } from '../config/layout';
import { PLUGIN_PREFIX as _PLUGIN_PREFIX } from '../constants';
import type { PluginSchemaSource } from '../schema/schema';
import type { SpaceGraph } from '../space-graph';
import type { SpaceGraphData } from '../space-graph-data';
import type { BaseNode, ParseIssue, SpaceContext, ValidationIssue } from '../types';
import type { ValidateSpaceOptions } from '../validate';
import { isBuiltinPluginName } from './builtin-names';

export const PLUGIN_PREFIX = _PLUGIN_PREFIX;
export const CONFIG_PLUGINS_DIR = 'plugins';

/** Normalize a plugin name to its canonical prefixed form. */
export function normalizePluginName(name: string): string {
  return name.startsWith(PLUGIN_PREFIX) ? name : `${PLUGIN_PREFIX}${name}`;
}

/** Shorten a plugin name to its non-prefixed form. */
export function shortenPluginName(name: string): string {
  return name.startsWith(PLUGIN_PREFIX) ? name.slice(PLUGIN_PREFIX.length) : name;
}

export type PluginContext = SpaceContext & {
  /** Validated config for this plugin invocation. */
  pluginConfig: Record<string, unknown>;
  /** Optional callback functions for plugins to interact with the system. */
  callbacks?: {
    /** Persist plugin config updates to the config file. */
    persistConfig?: (updates: Record<string, string>) => void;
    /** Validate the whole space and return every issue found, of every severity. */
    validate?: (
      options?: Pick<ValidateSpaceOptions, 'includeGated' | 'ruleFilter' | 'semantic' | 'depth'>,
    ) => Promise<ValidationIssue[]>;
    /** The graph being rendered, in the space graph format. */
    exportGraph?: () => SpaceGraphData;
    /** Every folder of one kind of resource (such as `map-views`), with the plugin providing it if any. */
    resourceDirs?: (kind: string) => Array<{ dir: string; plugin?: string }>;
  };
};

export type ParseResult = {
  nodes: BaseNode[];
  /** Issues encountered while parsing files — excluded files with reason and severity. */
  parseIssues: ParseIssue[];
  /** Pages read but not made nodes, such as files without a type. Content links to them resolve. */
  excludedPages?: Array<Required<Pick<BaseNode, 'source' | 'linkTargets'>>>;
  /** Plugin diagnostics: keyed scalar or list values. */
  diagnostics: Record<string, number | string | string[]>;
};

export type ParseHook = (context: PluginContext) => Promise<ParseResult | null>;

export type TemplateSyncOptions = {
  dryRun?: boolean;
  createMissing?: boolean;
};

export type TemplateSyncHook = (context: PluginContext, options: TemplateSyncOptions) => Promise<true | null>;

/** A single render output format provided by a plugin. */
export type RenderFormat = {
  /** Short name, unique within the plugin (e.g. 'bullets', 'mermaid'). */
  name: string;
  /** Human-readable description shown in `render list`. */
  description: string;
};

/** Options passed to a render function. */
export type RenderOptions = {
  /** The format name being rendered (e.g. 'bullets', 'mermaid'). */
  format: string;
  /** Plugin-specific extra data (e.g. CLI flags forwarded by a convenience command). */
  data?: Record<string, unknown>;
};

/** A single file generated as part of a multi-file render output. */
export type RenderFileOutput = {
  /** Relative path of the file within the destination directory (e.g. 'goals/My Goal.md'). */
  path: string;
  /** File content to write. */
  content: string;
};

/** Multi-file render output generated by a render hook. */
export type RenderMultiFileOutput = {
  files: RenderFileOutput[];
};

/** Render hook output: either a single string (stdout/single file) or multiple files. */
export type RenderResult = string | RenderMultiFileOutput;

/** Type guard for multi-file render result. */
export function isRenderMultiFileOutput(result: RenderResult): result is RenderMultiFileOutput {
  return typeof result === 'object' && result !== null && Array.isArray((result as RenderMultiFileOutput).files);
}

/**
 * The render hook on a plugin: declares available formats and handles rendering.
 * Unlike parse/templateSync (first-responder), render hooks are additive —
 * all formats from all plugins are available simultaneously.
 */
export type RenderHook = {
  formats: RenderFormat[];
  render: (context: PluginContext, graph: SpaceGraph, options: RenderOptions) => Promise<RenderResult> | RenderResult;
};

/**
 * Plugin contract:
 * - A hook not implemented on the plugin → that plugin is skipped for that operation.
 * - parse/templateSync return `T | null` → null means "didn't handle, try next plugin".
 * - render is additive: all plugins' formats are registered and dispatched by name.
 */
export type StructuredContextPlugin = {
  name: string;
  /** JSON Schema used to validate the plugin's config block. Fields with `format: 'path'`
   * are resolved relative to the config directory by `resolveConfigPaths` in the loader. */
  configSchema: AnySchemaObject;
  /** Optional directory containing JSON schemas contributed by this plugin. */
  schemasDir?: string;
  parse?: ParseHook;
  templateSync?: TemplateSyncHook;
  render?: RenderHook;
};

function isDirectory(path: string): boolean {
  return existsSync(path) && statSync(path).isDirectory();
}

/** A plugin's root directory: in the config root's plugins folder, else by module resolution from configDir. */
export function resolvePluginDir(pluginName: string, configDir: string): string | undefined {
  const candidates = [normalizePluginName(pluginName), shortenPluginName(pluginName)];

  const pluginsDir = resourceDir(configDir, CONFIG_PLUGINS_DIR);
  const local = pluginsDir && candidates.map((c) => resolve(pluginsDir, c)).find(isDirectory);
  if (local) return local;

  const req = createRequire(join(configDir, 'package.json'));
  for (const candidate of candidates) {
    try {
      return dirname(req.resolve(`${candidate}/package.json`));
    } catch {
      // Not resolvable as a package; a package without a package.json export may still sit in node_modules.
      const installed = resolve(configDir, 'node_modules', candidate);
      if (isDirectory(installed)) return installed;
    }
  }
  return undefined;
}

/** A plugin's folder for one kind of resource: the folder its package.json names under `sctx`, else `<pluginDir>/<kind>`. */
function pluginResourceDir(pluginDir: string, kind: string): string | undefined {
  const pkgJsonPath = join(pluginDir, 'package.json');
  const named = existsSync(pkgJsonPath) ? JSON.parse(readFileSync(pkgJsonPath, 'utf8')).sctx?.[kind] : undefined;
  const dir = typeof named === 'string' ? resolve(pluginDir, named) : join(pluginDir, kind);
  return isDirectory(dir) ? dir : undefined;
}

/** A plugin's schemas folder, else the plugins folder's `schemas/` (used by test fixtures). */
export function resolvePluginSchemasDir(pluginName: string, configDir: string): string | undefined {
  const dir = resolvePluginDir(pluginName, configDir);
  const own = dir && pluginResourceDir(dir, SCHEMAS_RESOURCE);
  if (own) return own;
  const pluginsDir = resourceDir(configDir, CONFIG_PLUGINS_DIR);
  const shared = pluginsDir && resolve(pluginsDir, SCHEMAS_RESOURCE);
  return shared && isDirectory(shared) ? shared : undefined;
}

/** The non-built-in plugins a space names, by schema prefix or in `plugins`. */
function spacePluginNames(space: SpaceConfig | undefined, config: Config): string[] {
  const schema = (space?.schema ?? config.schema)?.replace(/\\/g, '/');
  const schemaPlugin =
    schema && !isAbsolute(schema) && !schema.startsWith('.') && schema.includes('/') ? [schema.split('/')[0]!] : [];
  const topLevel = (config as { plugins?: Record<string, unknown> }).plugins ?? {};
  const names = [...schemaPlugin, ...Object.keys(space?.plugins ?? {}), ...Object.keys(topLevel)];
  // Resolving a built-in as a package can query the npm registry or find an unrelated package such as `markdown`.
  return [...new Set(names.map(shortenPluginName))].filter((name) => !isBuiltinPluginName(name));
}

/** Synchronously collect all plugin schema sources available to a space. */
export function resolveSpacePluginSchemas(
  space: SpaceConfig | undefined,
  config: Config,
  configDir: string,
): PluginSchemaSource[] {
  return spacePluginNames(space, config).flatMap((pluginName) => {
    const schemasDir = resolvePluginSchemasDir(pluginName, configDir);
    return schemasDir ? [{ pluginName, schemasDir }] : [];
  });
}

/** Every folder of one kind of resource for a space: its config root's first, then its plugins'. */
export function resourceDirs(context: SpaceContext, kind: string): Array<{ dir: string; plugin?: string }> {
  const { configDir } = context;
  const pluginsDir = resourceDir(configDir, CONFIG_PLUGINS_DIR);
  const folderPlugins = pluginsDir
    ? readdirSync(pluginsDir, { withFileTypes: true })
        .filter((e) => e.isDirectory() && e.name.startsWith(PLUGIN_PREFIX))
        .map((e) => shortenPluginName(e.name))
    : [];
  const plugins = [...new Set([...folderPlugins, ...spacePluginNames(context.space, context.config)])];

  const own = resourceDir(configDir, kind);
  return [
    ...(own ? [{ dir: own }] : []),
    ...plugins.flatMap((plugin) => {
      const pluginDir = resolvePluginDir(plugin, configDir);
      const dir = pluginDir && pluginResourceDir(pluginDir, kind);
      return dir ? [{ dir, plugin }] : [];
    }),
  ];
}
